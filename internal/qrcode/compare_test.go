// 参考矩阵来自 Nayuki qrcodegen 对 "http://127.0.0.1:8080" (Ecc.MEDIUM, version 2, size 25)
// 的权威输出。逐模块比对可用于定位编码 bug。
const refSize = 25

var refRows = []string{
	"1111111011010000101111111",
	"1000001011000110001000001",
	"1011101011000100101011101",
	"1011101001010111001011101",
	"1011101010110000001011101",
	"1000001001101000001000001",
	"1111111010101010101111111",
	"0000000000011110000000000",
	"1001111111010001010010111",
	"1010110100101101110011110",
	"1000011111011011001001001",
	"0010000101101001000001111",
	"1010001000111010111000001",
	"1011100101000101000110010",
	"1111101110011101110001111",
	"1000010001010010100010101",
	"1000111100100011111110110",
	"0000000011011101100010010",
	"1111111010010000101011001",
	"1000001011001010100010011",
	"1011101010001111111111011",
	"1011101010000010001101011",
	"1011101000101010100010111",
	"1000001001000010011110111",
	"1111111011100111111001001",
}

func TestCompareNayuki(t *testing.T) {
	data := []byte("http://127.0.0.1:8080")
	modules, err := Encode(data, Medium)
	if err != nil {
		t.Fatal(err)
	}
	n := len(modules)
	if n != refSize {
		t.Fatalf("版本/边长不符: got %d, want %d", n, refSize)
	}

	diff := 0
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			want := refRows[y][x] == '1'
			got := modules[y][x]
			if got != want {
				diff++
				if diff <= 20 {
					t.Logf("diff at (x=%d,y=%d): got=%v want=%v", x, y, got, want)
				}
			}
		}
	}
	if diff > 0 {
		t.Fatalf("与 Nayuki 参考实现不一致的模块数: %d", diff)
	}
}
