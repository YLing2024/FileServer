// numDataCodewords 返回某版本+等级的总数据码字数。
func numDataCodewords(version int, l Level) int {
	e := eccTable(version, l)
	return e.group1Num*e.group1Data + e.group2Num*e.group2Data
}

// encodeBits 构建字节模式的完整数据位流（含模式指示、长度、数据、终止符、填充），
// 返回按码字对齐的数据码字序列。
func encodeBits(data []byte, version int, l Level) ([]byte, error) {
	n := numDataCodewords(version, l)
	capacityBits := n * 8

	b := &bitBuf{}

	// 模式指示 0100
	b.append(0x4, 4)

	// 字符计数指示（字节数）
	var countBits int
	if version <= 9 {
		countBits = 8
	} else {
		countBits = 16
	}
	b.append(len(data), countBits)

	// 数据字节
	for _, c := range data {
		b.append(int(c), 8)
	}

	// 终止符：最多 4 个 0 位（受容量限制）
	rem := capacityBits - b.len()
	if rem > 4 {
		rem = 4
	}
	b.append(0, rem)

	// 补齐到字节边界
	if b.len()%8 != 0 {
		b.append(0, 8-b.len()%8)
	}

	// 填充码字 0xEC, 0x11 交替，直到填满
	pad := [2]byte{0xEC, 0x11}
	p := 0
	for b.len() < capacityBits {
		b.append(int(pad[p]), 8)
		p ^= 1
	}

	bs := b.bytes()
	if len(bs) != n {
		return nil, errors.New("qrcode: 内部错误，码字长度不一致")
	}
	return bs, nil
}

// rsEncode 将数据码字分块、逐块 RS 编码、并按 QR 规则交错，返回完整码字序列
// （数据码字 + 纠错码字，交错后排列）。
func rsEncode(data []byte, version int, l Level) ([]byte, error) {
	e := eccTable(version, l)

	// 分块
	type block struct {
		data []byte
		ecc  []byte
	}
	var blocks []block
	off := 0
	for i := 0; i < e.group1Num; i++ {
		d := data[off : off+e.group1Data]
		off += e.group1Data
		ecc := rsEncodeBytes(d, e.ecPerBlock)
		blocks = append(blocks, block{d, ecc})
	}
	for i := 0; i < e.group2Num; i++ {
		d := data[off : off+e.group2Data]
		off += e.group2Data
		ecc := rsEncodeBytes(d, e.ecPerBlock)
		blocks = append(blocks, block{d, ecc})
	}

	// 交错：先所有块的数据码字逐轮交错，再纠错码字逐轮交错
	var out []byte
	maxData := e.group1Data
	if e.group2Data > maxData {
		maxData = e.group2Data
	}
	for i := 0; i < maxData; i++ {
		for _, blk := range blocks {
			if i < len(blk.data) {
				out = append(out, blk.data[i])
			}
		}
	}
	for i := 0; i < e.ecPerBlock; i++ {
		for _, blk := range blocks {
			out = append(out, blk.ecc[i])
		}
	}
	return out, nil
}

// bitBuf 是一个简单的位写入器。
type bitBuf struct {
	bits []byte
	n    int
}

func (b *bitBuf) append(val int, count int) {
	for i := count - 1; i >= 0; i-- {
		if val>>uint(i)&1 == 1 {
			b.bits = append(b.bits, 1)
		} else {
			b.bits = append(b.bits, 0)
		}
	}
	b.n += count
}

func (b *bitBuf) len() int { return b.n }

func (b *bitBuf) bytes() []byte {
	out := make([]byte, len(b.bits)/8)
	for i := range out {
		var v byte
		for j := 0; j < 8; j++ {
			v = v<<1 | b.bits[i*8+j]
		}
		out[i] = v
	}
	return out
}
